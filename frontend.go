package gosqa

import (
	_ "embed"
	"encoding/binary"
	"math"
	"math/cmplx"

	"gonum.org/v1/gonum/dsp/fourier"
)

const (
	// SampleRate is the only sample rate supported by the bundled checkpoint.
	SampleRate = 48000
	// DefaultFrameSamples is the upstream default: two seconds of mono PCM.
	DefaultFrameSamples = 2 * SampleRate
	// MinFrameSamples is the minimum that yields a complete 15-bin segment.
	MinFrameSamples = 14 * 480
	// MaxFrameSamples bounds per-call working memory to ten seconds of PCM.
	MaxFrameSamples = 10 * SampleRate
	fftSize         = 960
	hopSize         = 480
	melBands        = 48
	segmentWidth    = 15
	segmentHop      = 3
)

// Generated by tools/export.py from the pinned torchaudio configuration.
//
//go:embed models/frontend.bin
var frontendData []byte

var window, filterbank = frontendConstants()

func frontendConstants() ([fftSize]float32, [fftSize/2 + 1][melBands]float32) {
	var w [fftSize]float32
	var fb [fftSize/2 + 1][melBands]float32
	offset := 0
	next := func() float32 {
		v := math.Float32frombits(binary.LittleEndian.Uint32(frontendData[offset:]))
		offset += 4
		return v
	}
	for i := range w {
		w[i] = next()
	}
	for i := range fb {
		for j := range fb[i] {
			fb[i][j] = next()
		}
	}
	return w, fb
}

type frontend struct {
	fft      *fourier.FFT
	input    [fftSize]float64
	spectrum [fftSize/2 + 1]complex128
	mel      []float32
	segments []float32
}

func newFrontend() frontend { return frontend{fft: fourier.NewFFT(fftSize)} }

func resize(b []float32, n int) []float32 {
	if cap(b) < n {
		return make([]float32, n)
	}
	return b[:n]
}

// extract matches upstream's centered, reflect-padded, periodic Hann STFT,
// magnitude (not power) HTK mel transform, dB conversion, and segment stride.
func (f *frontend) extract(pcm []float32) ([]float32, int) {
	bins := len(pcm)/hopSize + 1
	f.mel = resize(f.mel, bins*melBands)
	peak := float32(-math.MaxFloat32)
	for t := range bins {
		for j := range f.input {
			i := t*hopSize + j - fftSize/2
			if i < 0 {
				i = -i
			}
			if i >= len(pcm) {
				i = 2*len(pcm) - 2 - i
			}
			f.input[j] = float64(pcm[i] * window[j])
		}
		f.fft.Coefficients(f.spectrum[:], f.input[:])
		var mel [melBands]float32
		for i, c := range f.spectrum {
			magnitude := float32(cmplx.Abs(c))
			for m, weight := range filterbank[i] {
				mel[m] += magnitude * weight
			}
		}
		for m, amplitude := range mel {
			db := float32(20 * math.Log10(float64(max(amplitude, 1e-4))))
			f.mel[m*bins+t] = db
			peak = max(peak, db)
		}
	}
	for i, v := range f.mel {
		f.mel[i] = max(v, peak-80)
	}
	count := (bins-segmentWidth)/segmentHop + 1
	f.segments = resize(f.segments, count*melBands*segmentWidth)
	for s := range count {
		for m := range melBands {
			copy(f.segments[(s*melBands+m)*segmentWidth:], f.mel[m*bins+s*segmentHop:m*bins+s*segmentHop+segmentWidth])
		}
	}
	return f.segments, count
}
